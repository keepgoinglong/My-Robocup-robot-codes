"""Run on the PC to regenerate the single-file CanMV entry point."""
from pathlib import Path


def build():
    root = Path(__file__).resolve().parent
    entry = (root / "main_modular.py").read_text(encoding="utf-8")
    entry = entry.replace("from boundary_tracker import BoundaryTracker as LaneTracker, resolve_control\n", "")
    entry = entry.replace("from motion_feedback import MotionFeedback\n", "")
    entry = entry.replace("from lane_protocol import encode, encode_angle, encode_obstacle\n", "")
    entry = entry.replace("from angle_tracker import AngleTracker\n", "")
    entry = entry.replace("from shape_tracker import CardRecognizer, ShapeEvents, board_candidates\n", "")
    entry = entry.replace("from obstacle_tracker import ObstacleTracker\n", "")
    config, implementation = entry.split("\ndef native_runs", 1)
    parts = [
        '# Single-file CanMV K230D program. Open this file in CanMV IDE and run.\n'
        '# Generated by build_standalone.py; no project modules to upload.\n',
        config,
        (root / "line_tracker.py").read_text(encoding="utf-8").split("class LaneTracker:")[0],
        (root / "boundary_tracker.py").read_text(encoding="utf-8").replace("from line_tracker import quadratic\n", ""),
        "LaneTracker = BoundaryTracker\n",
        (root / "angle_tracker.py").read_text(encoding="utf-8"),
        (root / "lane_protocol.py").read_text(encoding="utf-8"),
        (root / "motion_feedback.py").read_text(encoding="utf-8").replace("from lane_protocol import crc16\n", ""),
        (root / "shape_tracker.py").read_text(encoding="utf-8"),
        (root / "obstacle_tracker.py").read_text(encoding="utf-8"),
        "def native_runs" + implementation,
    ]
    target = root / "canmv_line_follow_single.py"
    target.write_text("\n\n".join(parts), encoding="utf-8")
    (root / "main.py").write_text("\n\n".join(parts), encoding="utf-8")
    print(target)


if __name__ == "__main__":
    build()
